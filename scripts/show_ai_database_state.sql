-- =====================================================================
-- FLASHDROP: scripts/show_ai_database_state.sql
-- All-in-One Live Database Inspection Script for Teacher Presentation
-- Shows all database entities, records, and mutations touched by FlashDrop AI
-- =====================================================================

USE flashdrop;

-- =====================================================================
-- 1. ISOLATED CUSTOMER PERSONAS & WALLET BALANCES (Multi-Tenant Isolation)
-- =====================================================================
SELECT 
    '1. MULTI-TENANT USER PERSONAS & WALLET BALANCES' AS audit_section;

SELECT 
    u.user_id,
    CONCAT(u.first_name, ' ', u.last_name) AS full_name,
    u.email,
    r.role_name,
    u.status AS account_status,
    COALESCE(w.balance, 0.00) AS wallet_balance_usd,
    COALESCE(lt.tier_name, 'None') AS loyalty_tier,
    COALESCE(fn_calculate_loyalty_discount(u.user_id), 0.00) AS discount_pct
FROM users u
INNER JOIN roles r ON u.role_id = r.role_id
LEFT JOIN wallets w ON u.user_id = w.user_id
LEFT JOIN user_tiers ut ON u.user_id = ut.user_id
LEFT JOIN loyalty_tiers lt ON ut.tier_id = lt.tier_id
WHERE u.user_id IN (1, 2, 3, 4, 5, 6, 1001)
ORDER BY u.user_id;

-- =====================================================================
-- 2. FINANCIAL LEDGER MUTATIONS (Double-Entry Ledger Audit Trail)
-- =====================================================================
SELECT 
    '2. FINANCIAL LEDGER TRANSACTIONS TOUCHED BY AI/CHECKOUT' AS audit_section;

SELECT 
    wl.ledger_id,
    wl.wallet_id,
    w.user_id,
    u.first_name AS customer_name,
    wl.entry_type,
    wl.amount,
    wl.balance_after,
    wl.reference_type,
    wl.description,
    wl.created_at
FROM wallet_ledger wl
INNER JOIN wallets w ON wl.wallet_id = w.wallet_id
INNER JOIN users u ON w.user_id = u.user_id
WHERE w.user_id IN (1, 2, 3, 4, 5, 6, 1001)
ORDER BY wl.ledger_id DESC
LIMIT 8;

-- =====================================================================
-- 3. CONFIRMED ORDERS TRACKED BY AI CONCIERGE
-- =====================================================================
SELECT 
    '3. CONFIRMED ORDERS & BILLING RECEIPTS QUERIED BY AI' AS audit_section;

SELECT 
    o.order_id,
    o.order_number,
    o.user_id,
    u.first_name AS customer,
    d.title AS drop_title,
    o.total_amount,
    o.discount_amount,
    o.final_amount,
    o.status AS order_status,
    o.created_at
FROM orders o
INNER JOIN users u ON o.user_id = u.user_id
INNER JOIN drops d ON o.drop_id = d.drop_id
WHERE o.user_id IN (2, 3, 4, 5, 6, 1001)
ORDER BY o.order_id DESC
LIMIT 6;

-- =====================================================================
-- 4. IMMUTABLE JSON AUDIT LOG POPULATED BY TRIGGERS
-- =====================================================================
SELECT 
    '4. IMMUTABLE JSON AUDIT LOG (Generated by MySQL Triggers)' AS audit_section;

SELECT 
    log_id,
    table_name,
    action,
    record_id,
    new_values_json,
    created_at
FROM audit_log
ORDER BY log_id DESC
LIMIT 5;

-- =====================================================================
-- 5. ANTI-BOT & FRAUD TELEMETRY FLAGGED IN DB
-- =====================================================================
SELECT 
    '5. HIGH-RISK BOT ATTACK ANOMALIES & AUTO-SUSPENDED ACCOUNTS' AS audit_section;

SELECT 
    f.flag_id,
    u.user_id,
    CONCAT(u.first_name, ' ', u.last_name) AS user_name,
    u.email,
    u.status AS current_status,
    f.risk_score,
    f.flag_reason,
    f.flagged_at
FROM fraud_flags f
INNER JOIN users u ON f.user_id = u.user_id
ORDER BY f.risk_score DESC
LIMIT 5;

-- =====================================================================
-- 6. REAL-TIME STOREFRONT INVENTORY & SELLOUT AGGREGATION VIEW
-- =====================================================================
SELECT 
    '6. STOREFRONT INVENTORY CONSERVATION & SALES SUMMARY VIEW' AS audit_section;

SELECT 
    drop_id,
    drop_title,
    drop_status,
    drop_price,
    total_allocated,
    sold_quantity,
    available_quantity,
    sellout_rate_pct,
    total_paid_orders,
    total_revenue_usd
FROM vw_admin_sales_summary;
